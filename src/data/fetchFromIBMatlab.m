function bardata = fetchFromIBMatlab(symbol, duration, barSize)
% Price collection with IBMatlab (including error correction)
    bardata = struct('Timestamp',[], 'Open',[], 'High',[], ...
                     'Low',[], 'Close',[], 'Volume',[]);
    try
        params = struct( ...
            'action', 'history', ...
            'symbol', symbol, ...
            'secType', 'STK', ...
            'exchange', 'SMART', ...
            'currency', 'USD', ...
            'barSize', barSize, ...
            'useRTH', 0, ...
            'whatToShow', 'TRADES', ...
            'duration', duration, ...
            'endDateTime', '', ...
            'formatDate', 1 ...
        );

        data = IBMatlab(params);

        if isempty(data) || isempty(data.dateTime)
            warning('No data received for %s', symbol);
            return;
        end

        if iscell(data.dateTime)
            dtList = string(data.dateTime);
        else
            dtList = string({data.dateTime});
        end
        bardata.Timestamp = datetime(dtList, 'InputFormat','yyyyMMdd  HH:mm:ss');

        bardata.Open   = data.open(:);
        bardata.High   = data.high(:);
        bardata.Low    = data.low(:);
        bardata.Close  = data.close(:);
        bardata.Volume = data.volume(:);

    catch ME
        warning('[%s] Async fetch failed for %s: %s', ...
            datestr(now,'HH:MM:SS'), symbol, ME.message);
    end
end